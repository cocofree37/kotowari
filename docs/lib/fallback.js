// 調子・気分から、今日のモードを決める
function modeOf(c) {
  if (c.mood === '不安') return 'prepare';
  if (c.mood === 'イライラ') return 'calm';
  if (c.energy <= 2 || c.mood === '疲れ気味' || (c.sleep === '短め' && c.energy <= 3)) return 'recover';
  if (c.energy >= 4) return 'attack';
  return 'steady';
}

