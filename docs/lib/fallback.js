const clamp = (n) => Math.max(1, Math.min(5, n));

export function fallbackReading(facts, condition, note) {
  const c = { ...condition, energyLabel: ['', 'ぐったり', 'いまいち', 'ふつう', '好調', '絶好調'][condition.energy] };
  const mode = MODES[modeOf(c)];
  const f = FOCUS[c.focus];
  const [theme, strength] = LIFE_PATH[facts.lifePath];
  const [relTitle, relText] = RELATION[facts.relation.kind];
  const t = facts.today;
  const el = facts.relation.todayElement;
  const lucky = LUCKY[el];

  const relAdj = { receives: 1, controls: 1, same: 0, gives: 0, controlled: -1 }[facts.relation.kind];
  const sleepAdj = { 短め: -1, ふつう: 0, しっかり: 1 }[c.sleep];
  const [s0, s1, s2] = mode.scores;

  const memoLine = c.memo ? `\n\n「${c.memo}」──メモにあった気持ち、ちゃんと受け取りました。今日はまず、そこに向き合う時間を一つだけ確保しましょう。` : '';

  return {
    source: 'fallback',
    headline: `今日の気の流れは「${relTitle}」`,
    mode: { name: mode.name, reason: `調子「${c.energyLabel}」・気分「${c.mood}」に、今日の気の流れ「${relTitle}」を重ねて判断しました。` },
    mantra: mode.mantra,
    meter: {
      focus: clamp(s0 + sleepAdj + (relAdj > 0 ? 1 : 0)),
      communication: clamp(s1 + (c.mood === '前向き' ? 1 : 0) + (relAdj < 0 ? -1 : 0)),
      decision: clamp(s2 + relAdj),
    },
    boost: mode.boost(c) + memoLine + `\n\n(※${note})`,
    face: { observed: false, impression: '', tip: '' },
    background:
      `今日の日柱は${t.dayPillar.name}、五行は「${el}」。あなたの日柱${facts.dayPillar.name}(${facts.relation.birthElement})との関係は「${relTitle}」です。${relText}\n\n` +
      `月は${t.moon.phase}(月齢${t.moon.age})。${MOON[t.moon.phase]}\n\n` +
      `${facts.sunSign}・ライフパス${facts.lifePath}「${theme}」のあなたの強みは「${strength}」。今日はこの強みが最も活きる場面に、時間を優先して配分しましょう。`,
    schedule: { morning: f.morning, afternoon: f.afternoon, evening: f.evening },
    missions: f.missions.map(([title, why]) => ({ title, why })),
    communication: f.communication,
    pitfall: mode.pitfall,
    reset: mode.reset,
    lucky: { color: lucky.color, item: lucky.item, direction: lucky.direction, time: BEST_TIME[el] },
  };
}
